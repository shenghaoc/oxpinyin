//! Build script: generates phf maps over the frozen syllable inventories.
//!
//! `src/syllables.rs` stays the single source of truth. This script extracts
//! the four `pub static … [&str; N]` tables' string entries and emits
//! `phf::Map<&'static str, u16>` statics (spelling → tier index) into
//! `OUT_DIR`; `src/syllables.rs` includes them. Generation is deterministic —
//! the same inventory produces byte-identical output — and fails the build
//! loudly if a table goes missing, changes shape, or repeats a spelling.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// `(source table, generated map)` pairs, in tier order: the order
/// `SyllableKey::from_text` / `from_canonical_text` consult them.
const TABLES: &[(&str, &str)] = &[
    ("FULL_PINYIN_SYLLABLES", "FULL_PINYIN_SYLLABLE_MAP"),
    ("INCOMPLETE_PINYIN_KEYS", "INCOMPLETE_PINYIN_KEY_MAP"),
    (
        "OPTION_ONLY_COMPLETE_SYLLABLES",
        "OPTION_ONLY_COMPLETE_SYLLABLE_MAP",
    ),
    (
        "ZHUYIN_ONLY_COMPLETE_SYLLABLES",
        "ZHUYIN_ONLY_COMPLETE_SYLLABLE_MAP",
    ),
];

fn main() {
    println!("cargo:rerun-if-changed=src/syllables.rs");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let source = fs::read_to_string("src/syllables.rs").expect("read src/syllables.rs");

    let mut generated =
        String::from("// Generated by build.rs from src/syllables.rs; do not edit.\n\n");
    for (table, map) in TABLES {
        let (declared, entries) = extract(&source, table)
            .unwrap_or_else(|| panic!("{table}: table not found in src/syllables.rs"));
        assert_eq!(
            entries.len(),
            declared,
            "{table}: declared [&str; {declared}] but found {} entries",
            entries.len()
        );
        let mut phf = phf_codegen::Map::new();
        for (index, entry) in entries.iter().enumerate() {
            // Codegen applies its own `{:?}` quoting to the key (`FmtConst`),
            // so the raw spelling goes in — debugging it here would
            // double-escape every entry.
            phf.entry(entry.clone(), index.to_string());
        }
        writeln!(
            generated,
            "pub(crate) static {map}: ::phf::Map<&'static str, u16> = {};",
            phf.build()
        )
        .expect("write generated map");
        writeln!(generated).expect("write generated map separator");
    }

    generate_zhuyin(&out_dir);
    fs::write(out_dir.join("syllable_maps.rs"), generated).expect("write syllable_maps.rs");
}

/// Extracts a frozen `pub static NAME: [&str; COUNT] = ["…", …];` table from
/// the syllable source, resolving `COUNT` through its
/// `pub const COUNT: usize = …;` definition: the declared length and the
/// string entries.
fn extract(source: &str, name: &str) -> Option<(usize, Vec<String>)> {
    let marker = format!("static {name}: [&str;");
    let table = source.find(&marker)?;
    let length_start = table + marker.len();
    let length_end = source[length_start..].find(']')? + length_start;
    let count_ident = source[length_start..length_end].trim();

    let count_marker = format!("const {count_ident}: usize = ");
    let count_start = source.find(&count_marker)? + count_marker.len();
    let count_end = source[count_start..].find(';')? + count_start;
    let declared = source[count_start..count_end].trim().parse().ok()?;

    // The assignment may wrap (`= \n    [`): find the `=` closing the
    // declaration, then the opening bracket after it.
    let eq = source[length_end..]
        .find('=')
        .unwrap_or_else(|| panic!("{name}: no array assignment found"))
        + length_end;
    let open = source[eq..]
        .find('[')
        .unwrap_or_else(|| panic!("{name}: no array body found"))
        + eq
        + 1;
    let close = source[open..]
        .find("];")
        .unwrap_or_else(|| panic!("{name}: unterminated array body"))
        + open;
    let body = &source[open..close];

    // The body holds only comma-separated string literals; the entries are
    // the quoted pieces.
    let mut pieces = body.split('"');
    pieces.next();
    let mut entries = Vec::new();
    while let Some(entry) = pieces.next() {
        entries.push(entry.to_owned());
        pieces.next();
    }
    Some((declared, entries))
}

/// Keep frozen Rust literals reviewable, but never compile their fat pointers
/// into production. Reject unexpected syntax rather than silently dropping rows.
fn generate_zhuyin(out_dir: &std::path::Path) {
    println!("cargo:rerun-if-changed=src/zhuyin_rows.rs");
    let source = fs::read_to_string("src/zhuyin_rows.rs").expect("read frozen Zhuyin rows");
    let mut pool = String::new();
    let mut spans = std::collections::BTreeMap::new();
    let mut rows = String::new();
    let mut count = 0;
    for line in source
        .lines()
        .filter(|line| line.trim_start().starts_with('('))
    {
        let fields: Vec<_> = line
            .trim()
            .strip_prefix('(')
            .unwrap()
            .strip_suffix("),")
            .expect("row terminator")
            .split(", ")
            .collect();
        assert_eq!(fields.len(), 4, "frozen row shape");
        let mut encoded = Vec::new();
        for field in &fields[..3] {
            let text = field
                .strip_prefix('"')
                .and_then(|s| s.strip_suffix('"'))
                .expect("literal string");
            assert!(!text.contains(['"', '\\']), "unescaped frozen literal");
            let span = *spans.entry(text.to_owned()).or_insert_with(|| {
                let start = u16::try_from(pool.len()).expect("pool offset fits u16");
                let len = u8::try_from(text.len()).expect("span length fits u8");
                pool.push_str(text);
                assert_eq!(
                    pool.get(usize::from(start)..usize::from(start) + usize::from(len)),
                    Some(text)
                );
                (start, len)
            });
            encoded.push(format!("TextSpan {{ start: {}, len: {} }}", span.0, span.1));
        }
        assert!(
            matches!(
                fields[3],
                "0" | "ZHUYIN_INCOMPLETE" | "ZHUYIN_CORRECT_SHUFFLE"
            ),
            "known exact flags"
        );
        writeln!(
            rows,
            "CompactRow {{ input: {}, canonical: {}, pinyin: {}, flags: {} }},",
            encoded[0], encoded[1], encoded[2], fields[3]
        )
        .unwrap();
        count += 1;
    }
    assert_eq!(count, 1493, "frozen row count");
    let generated = format!(
        "static ZHUYIN_POOL: &str = {pool:?};\nstatic ZHUYIN_ROWS: [CompactRow; ZHUYIN_PINYIN_COUNT] = [\n{rows}];\n"
    );
    fs::write(out_dir.join("zhuyin_compact.rs"), generated).expect("write compact Zhuyin data");
}
