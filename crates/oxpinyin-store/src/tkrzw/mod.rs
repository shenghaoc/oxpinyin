/// A tkrzw-backed store implementing both capability tiers.
///
/// Feature-gated behind `tkrzw`. See the module documentation for the
/// table framing and for how `write`'s atomicity is weaker than a
/// write-ahead-log backend's.
pub struct TkrzwStore {
    db: Db,
    read_only: bool,
}

/// Allocates `class` and opens `path` with the pin's `attach_options`
/// (`tkrzwdb_utils.h:32-46`): `writable` for `ATTACH_READWRITE`, and
/// `OPEN_NO_CREATE` unless `create` (`ATTACH_CREATE`). A failed open is
/// the error the status names; the object is dropped with it, closed and
/// deleted as the module docs describe.
fn open_store(
    class: Class,
    path: &Path,
    writable: bool,
    create: bool,
) -> Result<TkrzwStore, StoreError> {
    let mut db = Db::new(class);
    let options = if create { OPEN_DEFAULT } else { OPEN_NO_CREATE };
    check(&db.open(path, writable, options)?)?;
    Ok(TkrzwStore {
        db,
        read_only: !writable,
    })
}

/// `Bigram::attach(dbfile, ATTACH_READONLY)` (`ngram_tkrzwdb.cpp:86-99`): a
/// `HashDBM` opened read-only with `OPEN_NO_CREATE`.
