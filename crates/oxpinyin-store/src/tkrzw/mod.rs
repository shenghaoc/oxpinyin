/// `Status::SUCCESS` — pinned by number, with `adapter.cc`'s `static_assert`
/// against the library's enum, so an upstream renumbering fails the build
/// instead of silently misclassifying statuses.
const STATUS_SUCCESS: i32 = 0;
/// `Status::SYSTEM_ERROR` — the codes that came from the operating system,
/// reported as [`StoreError::Io`] so callers can branch on I/O failures the
/// way they do for the other backends.
const STATUS_SYSTEM_ERROR: i32 = 2;
/// `Status::PRECONDITION_ERROR` — what a file class answers before a
/// successful `Open` (`tkrzw_dbm_hash.cc:400-401`).
#[cfg(test)]
const STATUS_PRECONDITION_ERROR: i32 = 4;
/// `Status::NOT_FOUND_ERROR` — how the ordered walk signals that the
/// records ran out, which ends a scan successfully rather than failing it,
/// and how `Get` and `Remove` answer an absent key.
const STATUS_NOT_FOUND_ERROR: i32 = 7;

/// `File::OPEN_DEFAULT`: create the file when it is absent. The pin's
/// `attach_options` for `ATTACH_READWRITE | ATTACH_CREATE`
/// (`tkrzwdb_utils.h:32-46`) and its `save_db` temporaries.
const OPEN_DEFAULT: i32 = 0;
/// `File::OPEN_NO_CREATE`: fail on an absent file instead of creating it.
/// The pin's `attach_options` without `ATTACH_CREATE`, and its `load_db`
/// sources (`chewing_large_table2_tkrzwdb.cpp:101`, `ngram_tkrzwdb.cpp:55`).
const OPEN_NO_CREATE: i32 = 1 << 1;

// ── errors ────────────────────────────────────────────────────────

/// The message bytes of a status, lossily: tkrzw's messages are the
/// library's own text and `strerror` output, not guaranteed UTF-8, and a
/// mangled message must not turn into a panic (constitution §4).
fn message_text(status: &ffi::NativeStatus) -> String {
    status
        .message
        .as_ref()
        .map(|message| String::from_utf8_lossy(message.as_bytes()).into_owned())
        .unwrap_or_default()
}

/// The text of a non-I/O tkrzw status, carrying the code and message
/// verbatim.
fn status_message(code: i32, message: &str) -> String {
    if message.is_empty() {
        format!("tkrzw status {code}")
    } else {
        format!("tkrzw status {code}: {message}")
    }
}

/// Builds the error for a failed status, with the shape every backend
/// uses: I/O failures surface as [`StoreError::Io`], other statuses as a
/// backend error carrying the code and message verbatim.
fn status_error(status: &ffi::NativeStatus) -> StoreError {
    let message = message_text(status);
    match status.code {
        STATUS_SYSTEM_ERROR => StoreError::Io(std::io::Error::other(message)),
        code => StoreError::Backend(crate::BackendError::with_code(
            code,
            status_message(code, &message),
        )),
    }
}

/// Maps a status: `SUCCESS` is `Ok`, anything else the error it names.
fn check(status: &ffi::NativeStatus) -> Result<(), StoreError> {
    if status.code == STATUS_SUCCESS {
        Ok(())
    } else {
        Err(status_error(status))
    }
}

/// Like [`check`], but `NOT_FOUND_ERROR` means "the walk ended" (or, for
/// a point operation, "no such record"), so it comes back as `Ok(true)`
/// instead of an error.
fn check_end(status: &ffi::NativeStatus) -> Result<bool, StoreError> {
    match status.code {
        STATUS_SUCCESS => Ok(false),
        STATUS_NOT_FOUND_ERROR => Ok(true),
        _ => Err(status_error(status)),
    }
}

// ── key framing ───────────────────────────────────────────────────

/// Whether iteration has walked past `hi` and can stop.
fn past_upper(key: &[u8], hi: Bound<&[u8]>) -> bool {
    match hi {
        Bound::Unbounded => false,
        Bound::Included(bound) => key > bound,
        Bound::Excluded(bound) => key >= bound,
    }
}

