impl WriteStore for TkrzwStore {
    type Txn<'a> = TkrzwTxn<'a>;

    fn create(path: &Path) -> Result<Self, StoreError> {
        open(path, true)
    }

    fn create_hash(path: &Path) -> Result<Self, StoreError> {
        open_hash_create(path)
    }

    /// `FlexibleBigram::attach` (`flexible_ngram_tkrzwdb.h:128-187` at
    /// 074a2219): one `HashDBM`, opened with `OPEN_NO_CREATE`, and with
    /// `ATTACH_CREATE` opened again without it. A failed open without
    /// CREATE, or a failed retry, deletes the object with no `Close`
    /// (`:148-158`). The retry's signature `Set` is ignored (`:161-167`).
    fn attach_hash(
        path: &Path,
        mode: AttachMode,
        signature: (&[u8], &[u8]),
    ) -> Result<HashAttach<Self>, StoreError> {
        let writable = mode != AttachMode::ReadOnly;
        let mut db = Db::new(Class::Hash);
        if db.open(path, writable, OPEN_NO_CREATE)?.code == STATUS_SUCCESS {
            return Ok(HashAttach::Opened(TkrzwStore {
                db,
                read_only: !writable,
            }));
        }
        if mode != AttachMode::ReadWriteCreate
            || db.open(path, writable, OPEN_DEFAULT)?.code != STATUS_SUCCESS
        {
            db.delete();
            return Ok(HashAttach::Closed);
        }
        let (key, value) = signature;
        let _ = db.set(key, value);
        Ok(HashAttach::Created(
            TkrzwStore {
                db,
                read_only: false,
            },
            true,
        ))
    }

    fn set_raw(&self, key: &[u8], value: &[u8]) -> Result<(), StoreError> {
        self.db.set(key, value)
    }

    fn rewrite_raw(&self, rewrite: &mut crate::store::RecordRewrite<'_>) -> Result<(), StoreError> {
        check(&ffi::rewrite(
            &self.db.dbm,
            &mut crate::store::Rewriter(rewrite),
        ))
    }

    fn create_in_memory() -> Result<Self, StoreError> {
        Ok(open_in_memory())
    }

    /// `ChewingLargeTable2::save_db` / `PhraseLargeTable3::save_db`
    /// (`chewing_large_table2_tkrzwdb.cpp:111-130`,
    /// `phrase_large_table3_tkrzwdb.cpp:102-121` at 074a2219): `RemoveFile`
    /// (an `unlink`, missing file tolerated), a `TreeDBM` opened writable
    /// with `OPEN_DEFAULT` and default tuning, `copy_tkrzwdb`'s one `Set`
    /// per record in key order (`tkrzwdb_utils.h:48-74`),
    /// `Synchronize(false)`, then close. Inserting record by record lets
    /// the tree divide its leaves as the pin's does, so the pages match.
    fn write_user_index(
        path: &Path,
        records: impl FnOnce(&mut crate::store::RecordSink<'_>) -> Result<(), StoreError>,
    ) -> Result<(), StoreError> {
        crate::store::remove_if_present(path)?;
        let file = open(path, true)?;
        // `copy_tkrzwdb` asserts on a failed `Set` or source walk.
        crate::store::copy::copy(records, |key, value| file.db.set(key, value))?;
        file.db.synchronize(false)
    }

    fn write<R>(
        &self,
        f: impl FnOnce(&mut Self::Txn<'_>) -> Result<R, StoreError>,
    ) -> Result<R, StoreError> {
        self.write_with(true, f).map(|(out, _)| out)
    }

    /// `FlexibleBigram::store` and `remove` (`flexible_ngram_tkrzwdb.h:
    /// 236-246`, `:259-263` at 074a2219): the `Set` or `Remove` alone, its
    /// status the answer. The pin's `reset()` makes the one
    /// `Synchronize(false)` (`:84-90`), which [`WriteStore::flush`] is.
    fn write_deferred<R>(
        &self,
        f: impl FnOnce(&mut Self::Txn<'_>) -> Result<R, StoreError>,
    ) -> Result<(R, bool), StoreError> {
        self.write_with(false, f)
    }

    /// `m_db->Synchronize(false)` (`flexible_ngram_tkrzwdb.h:84-90`).
    fn flush(&self) -> Result<(), StoreError> {
        self.db.synchronize(false)
    }

    fn compact(&mut self) -> Result<(), StoreError> {
        if self.read_only {
            return Err(StoreError::ReadOnly);
        }
        // A file-backed store's one stable-storage point. It is no
        // longer where `pinyin_save` reaches storage:
        // `UserStore::save_reporting` still calls this, but on the in-memory session store (#621),
        // where the synchronize has nothing to do.
        self.db.synchronize(true)
    }
}

impl TkrzwStore {
    /// [`WriteStore::write`], with the end-of-commit soft sync when `sync`.
    fn write_with<R>(
        &self,
        sync: bool,
        f: impl FnOnce(&mut TkrzwTxn<'_>) -> Result<R, StoreError>,
    ) -> Result<(R, bool), StoreError> {
        if self.read_only {
            return Err(StoreError::ReadOnly);
        }
        let db = &self.db;
        let mut txn = TkrzwTxn {
            store: PhantomData,
            buffer: BTreeMap::new(),
        };
        // On `Err` the buffer dies with the transaction and nothing was
        // ever written: rollback is the absence of the apply below.
        let result = f(&mut txn)?;
        let found = commit(db, &txn.buffer, sync)?;
        Ok((result, found))
    }
}

// ── write transaction ─────────────────────────────────────────────

/// Applies a finished transaction's buffer with the pin's calls, one `Set`
/// or `Remove` per record in key order, then, when `sync`, the soft sync. Not
/// generic, so the many `write` closures share one copy of it. The answer
/// is false when a `Remove` found no record (`NOT_FOUND_ERROR`), which the
/// trait's `remove` treats as a no-op and `write_deferred` reports.
#[inline(never)]
fn commit(
    db: &Db,
    buffer: &BTreeMap<Vec<u8>, Option<Vec<u8>>>,
    sync: bool,
) -> Result<bool, StoreError> {
    let mut found = true;
    for (key, slot) in buffer {
        match slot {
            Some(value) => db.set(key, value)?,
            None => found &= db.remove(key)?,
        }
    }
    if sync && !buffer.is_empty() {
        // Soft: on a file-backed store the commit is visible and
        // process-crash durable, and `compact` is its hard sync. The
        // in-memory session store has no file for either level.
        db.synchronize(false)?;
    }
    Ok(found)
}

/// Buffers a write transaction's mutations until the apply in
/// [`WriteStore::write`].
///
/// Keys are the file's raw keys, applied in ascending order. A `None`
/// slot is a pending removal. The transaction borrows its store for its
/// lifetime.
pub struct TkrzwTxn<'db> {
    store: PhantomData<&'db Db>,
    buffer: BTreeMap<Vec<u8>, Option<Vec<u8>>>,
}

impl WriteTxn for TkrzwTxn<'_> {
    // The point operations stay out of line: the user store calls them from
    // hundreds of sites, and inlining each one's buffer insert into every
    // caller costs far more code than a direct call. Dispatch is static
    // either way.
    #[inline(never)]
    fn put_raw(&mut self, key: &[u8], value: &[u8]) -> Result<(), StoreError> {
        // The file's bare keyspace, so the row is exactly what
        // `get_raw`/`range_raw` read back on this backend.
        self.buffer.insert(key.to_vec(), Some(value.to_vec()));
        Ok(())
    }

    #[inline(never)]
    fn remove_raw(&mut self, key: &[u8]) -> Result<(), StoreError> {
        // The removal half of `put_raw`, on the same bare keyspace.
        self.buffer.insert(key.to_vec(), None);
        Ok(())
    }
}

// ── the user bigram's in-memory container ─────────────────────────

/// libpinyin's tkrzw user bigram as `Bigram::load_db` leaves it: an
/// in-memory `TinyDBM` (`ngram_tkrzwdb.cpp:48-63`) at its default bucket
/// count, filled from the `HashDBM` file by `copy_tkrzwdb`'s
/// iterator walk (`tkrzwdb_utils.h`), so its bucket walk is the pin's.
/// A known-empty container defers native construction until its first store.
pub struct TkrzwUserBigramDb {
    // Uninitialized means known-empty, not a failed native handle. Keep the
    // default TinyDBM once a load or the first Set constructs it. Allocation
    // failure moving from init to the first write is maintainer-accepted.
    db: std::cell::OnceCell<Db>,
}

/// `copy_tkrzwdb(src, destdb)` (`tkrzwdb_utils.h:48-74` at 074a2219): the
/// records of `src` in its iterator order, each handed to `set`.
/// `MakeIterator` comes before the copy's fatal phase: an iterator that is
/// not made is the pin's soft `return false` (`:52-54`), its own error. A
/// failed `Set` or a `Get` that ends in anything but `NOT_FOUND_ERROR` is
/// [`StoreError::FatalCopy`], where the copy asserts (`:65`, `:72`).
fn copy_tkrzwdb(
    src: &Db,
    set: impl FnMut(&[u8], &[u8]) -> Result<(), StoreError>,
) -> Result<(), StoreError> {
    #[cfg(feature = "test-hooks")]
    crate::store::copy::faults::make_iterator()?;
    let cursor = src.cursor()?;
    crate::store::copy::copy(
        |visit| {
            drive_cursor(
                cursor,
                Bound::Unbounded,
                Bound::Unbounded,
                &mut |key, value| {
                    visit(key, value)?;
                    Ok(Flow::Continue(()))
                },
            )
        },
        set,
    )
}

impl crate::store::UserBigramDb for TkrzwUserBigramDb {
    fn empty() -> Result<Self, StoreError> {
        // Defer `new TinyDBM` (`ngram_tkrzwdb.cpp:52`): it opens no file.
        // Empty reads and walks have no native state to preserve.
        Ok(Self {
            db: std::cell::OnceCell::new(),
        })
    }

    fn load_db(path: &Path) -> Result<Self, StoreError> {
        let this = Self::empty()?;
        // `HashDBM tmp_db; tmp_db.Open(dbfile, false, OPEN_NO_CREATE)`
        // then `copy_tkrzwdb(&tmp_db, m_db)` (`ngram_tkrzwdb.cpp:54-58`);
        // a file that does not open leaves the container empty, as the
        // pin's does, whatever the reason.
        let mut file = Db::new(Class::Hash);
        if file
            .open(path, false, OPEN_NO_CREATE)
            .is_ok_and(|status| status.code == STATUS_SUCCESS)
        {
            // `copy_tkrzwdb` copies nothing from a file with no live
            // record, but its HashDBM iterator still reads every bucket
            // slot, and `save_db` writes 1,048,583 of them whatever the
            // rows: about 329M instructions per init. A file tkrzw opens
            // healthy and counts empty leaves the container exactly as that
            // copy would, so it is not walked; every other file is.
            if holds_no_record(&file) {
                return Ok(this);
            }
            let db = this.db.get_or_init(|| Db::new(Class::Tiny));
            // `copy_tkrzwdb` asserts on a failed `Set` or source walk
            // (`tkrzwdb_utils.h:65`, `:72`): the init stops there. An
            // iterator that is not made leaves the container as it is, and
            // `load_db` ignores the copy's answer (`ngram_tkrzwdb.cpp:58`).
            if let Err(StoreError::FatalCopy) = copy_tkrzwdb(&file, |key, value| db.set(key, value))
            {
                return Err(StoreError::FatalCopy);
            }
        }
        Ok(this)
    }

    fn get(&self, key: &[u8], value: &mut Vec<u8>) -> Result<bool, StoreError> {
        if let Some(db) = self.db.get() {
            return db.get(key, value);
        }
        value.clear();
        Ok(false)
    }

    fn store(&self, key: &[u8], value: &[u8]) -> Result<(), StoreError> {
        self.db.get_or_init(|| Db::new(Class::Tiny)).set(key, value)
    }

    fn remove(&self, key: &[u8]) -> Result<(), StoreError> {
        // The trait's removal of an absent record is a no-op.
        if let Some(db) = self.db.get() {
            db.remove(key)?;
        }
        Ok(())
    }

    fn keys(&self) -> Result<Vec<Option<[u8; 4]>>, StoreError> {
        // `get_all_items`: one read-only `ProcessEach` whose processor
        // appends each key as a token (`ngram_tkrzwdb.cpp:143-172` at
        // 074a2219); a key of another length is `None` for the upper gate.
        let Some(db) = self.db.get() else {
            return Ok(Vec::new());
        };
        Ok(db
            .keys()?
            .into_iter()
            .map(|key| <[u8; 4]>::try_from(key).ok())
            .collect())
    }

    fn is_empty(&self) -> Result<bool, StoreError> {
        self.db.get().map_or(Ok(true), |db| Ok(db.count()? == 0))
    }

    fn save_db(&self, path: &Path) -> Result<(), StoreError> {
        save_bigram_db(self.db.get(), path)
    }
}

fn save_bigram_db(db: Option<&Db>, path: &Path) -> Result<(), StoreError> {
    // `Bigram::save_db` (`ngram_tkrzwdb.cpp:66-87`): remove the file,
    // open a fresh `HashDBM` at its default tuning, copy this
    // container into it in iterator order, synchronize, close.
    crate::store::remove_if_present(path)?;
    let file = open_hash_create(path)?;
    // `copy_tkrzwdb`: one `Set` per record (`tkrzwdb_utils.h:48-74`).
    // An empty source contributes no Set and no destination metadata. Keep
    // the native destination sequence, including its empty file and timestamp.
    // `save_db` ignores the copy's answer (`ngram_tkrzwdb.cpp:78`), so an
    // iterator that is not made goes on to the synchronize.
    if let Some(db) = db
        && let Err(StoreError::FatalCopy) = copy_tkrzwdb(db, |key, value| file.db.set(key, value))
    {
        return Err(StoreError::FatalCopy);
    }
    file.db.synchronize(false)
}

impl TkrzwStore {
    /// The tools' plain native `Set`, without synchronizing. Matches
    /// `ngram_tkrzwdb.cpp:124-132` and `punct_table_tkrzwdb.cpp:139-148`
    /// at 074a2219. The shipping transaction and durability path is unchanged.
    ///
    /// # Errors
    /// Returns the native write error, or an error for a read-only handle.
    #[cfg(feature = "tools")]
    pub fn tool_set(&self, key: &[u8], value: &[u8]) -> Result<(), StoreError> {
        if self.read_only {
            return Err(StoreError::ReadOnly);
        }
        self.db.set(key, value)
    }
}

