//! SyllableKey → TableKey encoder (frozen).
//!
//! The decoder works with [`pinyin_core::SyllableKey`] (u16 dense ids over the
//! 428 frozen keys), while the redb tables use 6-byte binary [`crate::types::TableKey`]
//! keys (the raw Tkrzw HashDB keys). The translation is a frozen lookup table
//! derived from the pinned oracle via FFI probe; see `docs/findings/syllable-encoder.md`.
//!
//! The table is pure, no I/O, no FFI at runtime — the mapping is baked in at compile time.
//! Incomplete keys (`b`..`zh`) map to `c0`-prefixed TableKeys that have no entry in
//! `pinyin_index.redb`; `SystemDictionary::lookup` for those will return an empty vec
//! for that syllable, which is the correct behaviour for segmentation-only keys.

use core::fmt;

use pinyin_core::SyllableKey;

use crate::types::TableKey;

/// Why a syllable could not be encoded.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum EncoderError {
    /// The syllable is not one of the 428 frozen keys (e.g., a future Stage 2 alias).
    Unknown {
        /// The syllable that was requested.
        syllable: SyllableKey,
    },
}

impl fmt::Display for EncoderError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Unknown { syllable } => write!(
                f,
                "unknown syllable-encoder: SyllableKey {} (id {}) has no TableKey mapping",
                syllable.text(),
                syllable.index()
            ),
        }
    }
}

impl std::error::Error for EncoderError {}

