//! tkrzw backend for the store capability tiers, over the pin's concrete
//! classes through cxx.
//!
//! Enabled by the `tkrzw` cargo feature. libpinyin at `074a2219` allocates
//! `TreeDBM`, `HashDBM`, `BabyDBM` and `TinyDBM` itself and calls them
//! through a `DBM*` member (`chewing_large_table2_tkrzwdb.cpp:57,87`,
//! `ngram_tkrzwdb.cpp:52,96`, `punct_table_tkrzwdb.cpp:38,70`,
//! `flexible_ngram_tkrzwdb.h:145`). [`Db`] is that member: one concrete
//! object behind `UniquePtr<DBM>`, constructed by [`Db::new`] and opened —
//! or not — by [`Db::open`], the pin's `new TreeDBM` and `m_db->Open(...)`
//! as two steps. The bridge (`bridge.rs`) is generated by cxx; its C++ side
//! (`adapter.cc`) is the semantic adapter the Rust/C++ interoperability
//! ruling permits (2026-11-02, `docs/findings/compatibility-policy.md`),
//! and it calls the library without copying or emulating any of it.
//!
//! The table's comparator is the class default: no pin call sets a tuning
//! parameter, comparator, update logger or file processor
//! (`docs/findings/tkrzw-native-call-inventory.md`), so `TreeDBM` and
//! `BabyDBM` sort by `LexicalKeyComparator` — plain unsigned byte order —
//! and oxpinyin's big-endian key codec keeps the ordering the byte-order
//! contract demands.
//!
//! # Reads copy once, as the pin's do
//!
//! A point read is the pin's `m_db->Get(key, &value)` into a `std::string`
//! (`ngram_tkrzwdb.cpp:111`, `chewing_large_table2_tkrzwdb.cpp:146`); the
//! bytes are then copied into the caller's buffer, as the pin copies them
//! into its `MemoryChunk` (`:117-118`, `:156-157`). A walk is the pin's
//! `copy_tkrzwdb` loop (`tkrzwdb_utils.h:48-74`): `MakeIterator`, `First`
//! or `Jump`, then `Get(&key, &value)` into two `std::string`s reused for
//! every record, and `Next`. The visitor borrows the strings' bytes for
//! the duration of one record; carrying a borrowed slice past that is the
//! one thing the design forbids, and the borrow checker enforces it. The
//! previous binding borrowed tkrzw's record memory through C callbacks
//! instead; the copy this binding makes per record is the pin's own.
//!
//! # Errors and status
//!
//! Every native status comes back as tkrzw's own code and message
//! (`bridge::ffi::NativeStatus`) and is handled where the pin handles it:
//! `SUCCESS` is `Ok`, `NOT_FOUND_ERROR` ends a walk or answers an existence
//! check, `SYSTEM_ERROR` — the codes that came from the operating system
//! (`tkrzw_lib_common.cc:247-278`, `GetErrnoStatus`) — is
//! [`StoreError::Io`], and every other code is a backend error carrying the
//! code and message verbatim. Nothing catches a C++ exception: the pin
//! catches none (`check_result` asserts, `pinyin_utils.h:27-31`; `xmalloc`
//! throws `std::bad_alloc`, `tkrzw_lib_common.h:147-183`), so an exception
//! ends the process through the bridge's `noexcept` shims, the abnormal
//! termination constitution §4 prescribes for a pin abort. Register row 40
//! recorded the previous binding's `SYSTEM_ERROR` report for a caught
//! exception, a classification this call path no longer makes; its
//! disposition is the maintainer's.
//!
//! # One keyspace, many tables
//!
//! A `TreeDBM` file is a single flat keyspace, while [`ReadStore`] and
//! [`WriteStore`] are addressed by `(table, key)`. Records are therefore
//! stored under `table-name || 0x00 || key`. The framing is prefix-free —
//! table names are validated NUL-free, so no framed prefix is a prefix of
//! another — which makes each table a contiguous run whose internal order
//! is the caller's key order, and makes `for_each`, `range` and `is_empty`
//! prefix scans. The framing is internal: nothing outside this module sees
//! it, and no file written by another backend is readable here or vice
//! versa.
//!
//! # Writes
//!
//! [`WriteStore::write`] buffers the closure's puts and removes, answers
//! in-closure reads from that buffer over the database, and on `Ok` applies
//! the buffer in framed-key order with the pin's calls: one `Set(key,
//! value)` per put (`ngram_tkrzwdb.cpp:132`) and one `Remove(key)` per
//! removal (`:140`), a removal of an absent record being the no-op the
//! trait contract names. On `Err` the buffer is dropped and nothing is
//! written. The pin has no multi-record operation, so neither has this
//! backend: another reader of a file-backed store can see a batch half
//! applied, and a crash during the apply can leave it so, as it could
//! leave the pin's own sequence of `Set`s. The previous binding applied a
//! batch through `ProcessMulti`, which the pin never calls; no caller
//! needs the all-records lock it took.
//!
//! Every non-empty commit then calls `Synchronize(false)`, the soft sync
//! the pin's `save_db` sequences end with (`ngram_tkrzwdb.cpp:80`,
//! `chewing_large_table2_tkrzwdb.cpp:126`): on a file-backed store the
//! buffered data is handed to the operating system, so the file is
//! consistent and visible to any reader and the write survives a process
//! crash. It is not yet on the device. [`WriteStore::compact`] is the hard
//! sync (`Synchronize(true)`), the one point at which a file-backed store
//! reaches stable storage; the pin never syncs hard, and the trait's
//! durability promise is the only reason the call exists. The previous
//! binding's `compact` also rebuilt the file (`Rebuild`), which the pin
//! never calls and no caller needs: its one shipping caller,
//! `UserStore::save`, compacts the in-memory session store, where both
//! calls do nothing (`tkrzw_dbm_baby.cc:583-596`).
//!
//! **The soft/hard split is measured, not assumed.** `hard=true` on every
//! commit costs +1.18–1.85 ms per commit here, because `TreeDBM` is
//! mmap-backed and the sync is two `msync(MS_SYNC)` calls over the whole
//! mapped region (~539 KiB) however few records the batch touched — a
//! 13–31× per-commit regression on a path the C ABI runs synchronously
//! from a keystroke. `docs/findings/perf-train-commit-fsync-2026-09-09.md`
//! carries the measurement and the decision.
//!
//! `compact` is no longer where `pinyin_save` reaches storage, though.
//! `UserStore::save` still calls it, but since the libpinyin session moved
//! into memory (#621) the store it compacts is the `BabyDBM` of
//! [`WriteStore::create_in_memory`], which has no file. The profile
//! `pinyin_save` writes goes out through `write_user_index` and the user
//! bigram's `save_db`, which synchronize soft (`hard=false`) before closing
//! — the level the pin's own `save_db` uses
//! (`chewing_large_table2_tkrzwdb.cpp:126`,
//! `phrase_large_table3_tkrzwdb.cpp:117`, `ngram_tkrzwdb.cpp:80`).
//!
//! # Object lifetime
//!
//! A [`Db`] is destroyed the way the pin's `reset()` destroys its member:
//! an explicit `Close()`, whose status is ignored, then `delete`
//! (`ngram_tkrzwdb.cpp:40-46`; the other owners synchronize soft first,
//! `chewing_large_table2_tkrzwdb.cpp:63-72`, which [`Db::synchronize`]
//! makes explicitly where the pin's owner does). The `Close` reaches a
//! never-opened object too and answers `PRECONDITION_ERROR` there
//! (`tkrzw_dbm_hash.cc:384-388`, `tkrzw_dbm_tree.cc:511-515`,
//! `tkrzw_dbm_baby.cc:394-398`, `tkrzw_dbm_tiny.cc:256-260`), as the
//! pin's does; the concrete destructors close only an object their own
//! state says is open (`tkrzw_dbm_hash.cc:248-254`,
//! `tkrzw_dbm_tree.cc:382-388`, `tkrzw_dbm_baby.cc:359-366`,
//! `tkrzw_dbm_tiny.cc:220-228`), so the explicit `Close` is the only one.
//! The pin's stack temporaries (`HashDBM tmp_db`) are closed explicitly
//! only when their `Open` succeeded; a [`Db`] that stands in for one
//! receives the same `Close` on both paths, which on the failed path is
//! the inert `PRECONDITION_ERROR` call above.
//!
//! A failed `Open` leaves the object exactly as the library leaves it, for
//! the owner to keep or drop. Every owner but `FlexibleBigram` keeps it
//! (`chewing_large_table2_tkrzwdb.cpp:87-88`, `ngram_tkrzwdb.cpp:96-98`,
//! `punct_table_tkrzwdb.cpp:70-72`); `FlexibleBigram` deletes it
//! (`flexible_ngram_tkrzwdb.h:147-159`). Which Rust owner keeps a failed
//! object is the owner's decision, made where the pin's owner makes it; the
//! store constructors in this module drop it, as they always did, and the
//! facade's system attachments keep it ([`open_system`], #1516). The
//! test `a_failed_open_retains_the_concrete_object_whose_calls_answer_as_the_pins`
//! proves the retained object is the native one.
//!
//! # Platform and the library build
//!
//! Linux-first, like the other evaluation backend: paths are handed to
//! tkrzw as bytes. The library must be discoverable via `pkg-config` and
//! must ship its C++ headers; `build.rs` says as much when they are
//! missing. The bridge is compiled by the crate's build script with the
//! flags `build.rs` documents.
//!
//! The library recognises `RecordProcessor::NOOP` and `REMOVE` by the
//! address of their backing bytes (`tkrzw_dbm.cc:26-37`,
//! `tkrzw_dbm_hash.cc:1474-1501`). A libtkrzw built with GCC's LTO before
//! tkrzw 1.0.34 holds several copies of those bytes (Ubuntu's 1.0.27 and
//! 1.0.32 packages; a source build under Arch's default flags) and
//! disagrees with itself about what a sentinel is: removing an absent
//! record stores one and removing a stored record leaves it in place, each
//! carrying the sentinel's five bytes as its value, while every write
//! reports success. The sentinels this backend returns are the header's
//! own objects (`adapter.cc`), so the fault can only be the library's;
//! nothing here checks for it at open. The store suite's
//! `tkrzw_library_honours_its_sentinel_protocol` names it, and
//! `docs/findings/tkrzw-distro-compat.md` carries the measurements.
//!
//! # Unsafe waiver
//!
//! This module and `bridge` each carry an explicit `expect(unsafe_code)`.
//! `bridge` declares the adapter's functions safe to call in an
//! `unsafe extern "C++"` block; this module holds the `unsafe impl Send`
//! and `Sync` for [`Db`] and states, at [`Db`], the claim every safe
//! declaration rests on. No raw pointer is dereferenced anywhere in the
//! backend. That waiver is scoped to the tkrzw backend by decision — the
//! workspace outside it stays `deny` — and it waives safety ceremony, not
//! correctness: the shared read and write suites gate this backend like
//! any other.
#![expect(
    unsafe_code,
    reason = "cxx bridge over libtkrzw; the Send/Sync impls carry their proof"
)]

