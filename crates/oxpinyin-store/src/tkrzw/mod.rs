/// The concrete class a [`Db`] was allocated as: the pin's `new TreeDBM`
/// (`chewing_large_table2_tkrzwdb.cpp:87`, `phrase_large_table3_tkrzwdb.
/// cpp:77`, `punct_table_tkrzwdb.cpp:70`, and the `save_db`/`load_db`
/// temporaries), `new HashDBM` (`ngram_tkrzwdb.cpp:96`,
/// `flexible_ngram_tkrzwdb.h:145`, the bigram temporaries), `new BabyDBM`
/// (`chewing_large_table2_tkrzwdb.cpp:57,98`,
/// `phrase_large_table3_tkrzwdb.cpp:46,89`, `punct_table_tkrzwdb.cpp:38,83`)
/// and `new TinyDBM` (`ngram_tkrzwdb.cpp:52`). The object keeps its class
/// for life.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Class {
    /// `TreeDBM`, the file-backed B+ tree of the index and punctuation
    /// tables.
    Tree,
    /// `HashDBM`, the file-backed hash table of the bigrams.
    Hash,
    /// `BabyDBM`, the on-memory B+ tree the tables load into.
    Baby,
    /// `TinyDBM`, the on-memory hash table the user bigram loads into.
    Tiny,
}

/// One native database object, the pin's `DBM* m_db`: a concrete class
/// allocated by [`Db::new`], opened — or not — by [`Db::open`], destroyed
/// by `Close` then `delete` when dropped.
///
/// # Safety claims (ruling point 1)
///
/// Every bridge function is declared safe to call. The claims:
///
/// - The object is non-null for its whole life: `new_*_dbm` return a fresh
///   allocation, `UniquePtr` keeps it, and nothing here releases it before
///   `Drop`.
/// - The record operations take `&DBM` and mutate the database behind it;
///   the classes document that "All operations are thread-safe; Multiple
///   threads can access the same database concurrently"
///   (`tkrzw_dbm_tree.h:36-40`, `tkrzw_dbm_hash.h:35-39`,
///   `tkrzw_dbm_baby.h:35-39`, `tkrzw_dbm_tiny.h:34-38`), and each
///   implementation takes its own mutex per call (`tkrzw_dbm_hash.cc:399`,
///   `tkrzw_dbm_tree.cc:562`). `open` and `close` take `Pin<&mut DBM>`:
///   they run with exclusive access, before the object is shared and in
///   `Drop`.
/// - Byte slices cross as borrowed views for one call; `Set` copies the key
///   and value into the record (`tkrzw_dbm.h:1123-1131`), `Open` copies
///   the path into a `std::string`, and no method retains a view.
/// - Out-parameters (`CxxString`, `CxxVector<CxxString>`, `i64`) are
///   assigned, never retained.
pub(crate) struct Db {
    dbm: UniquePtr<ffi::DBM>,
    /// Whether the owner's `reset()` calls `Synchronize(false)` before
    /// `Close`. Set only for a successfully opened system `TreeDBM`
    /// ([`open_system`]); every other holder closes without it, as its
    /// pin owner does.
    sync_before_close: bool,
}

impl Db {
    /// Allocates one object of `class` at its default tuning, not opened:
    /// the pin's `new TreeDBM` / `new HashDBM` / `new BabyDBM` /
    /// `new TinyDBM`. The on-memory classes are usable as they are.
    pub(crate) fn new(class: Class) -> Self {
        let dbm = match class {
            Class::Tree => ffi::new_tree_dbm(),
            Class::Hash => ffi::new_hash_dbm(),
            Class::Baby => ffi::new_baby_dbm(),
            Class::Tiny => ffi::new_tiny_dbm(),
        };
        Self {
            dbm,
            sync_before_close: false,
        }
    }

    /// `m_db->Open(dbfile, writable, options)`
    /// (`chewing_large_table2_tkrzwdb.cpp:88`). The status is the
    /// library's; on failure the object stays as the library left it,
    /// for the caller to keep or drop.
    ///
    /// # Errors
    ///
    /// Returns [`StoreError::InvalidInput`] for a path containing NUL,
    /// which `open(2)` would truncate, before any native call.
    pub(crate) fn open(
        &mut self,
        path: &Path,
        writable: bool,
        options: i32,
    ) -> Result<ffi::NativeStatus, StoreError> {
        validate_path(path)?;
        Ok(ffi::open(
            self.dbm.pin_mut(),
            path.as_os_str().as_encoded_bytes(),
            writable,
            options,
        ))
    }

    /// `delete m_db` with no `Close` (`flexible_ngram_tkrzwdb.h:148-158`):
    /// the virtual destructor runs now, and `Drop` finds a null owner.
    pub(crate) fn delete(&mut self) {
        self.dbm = UniquePtr::null();
    }

    /// Whether the native object is still owned: always, except after
    /// [`Self::delete`].
    #[cfg(test)]
    pub(crate) fn is_retained(&self) -> bool {
        !self.dbm.is_null()
    }

    /// `DBM::IsOpen()`: the library's own answer, which the owner never
    /// needs — it knows what `open` returned — and the retention test
    /// checks.
    #[cfg_attr(
        not(test),
        expect(dead_code, reason = "observed by the failed-open retention test")
    )]
    pub(crate) fn is_open(&self) -> bool {
        ffi::is_open(&self.dbm)
    }

    /// `m_db->Close()` ahead of `Drop`'s own, for the test that observes
    /// the status the pin's `reset()` ignores.
    #[cfg(test)]
    fn close(&mut self) -> ffi::NativeStatus {
        ffi::close(self.dbm.pin_mut())
    }

    /// `m_db->Get(key, &value)` (`ngram_tkrzwdb.cpp:111`), then the copy
    /// into the caller's buffer the pin makes into its chunk (`:117-118`).
    /// `value` is cleared first; the answer is whether the key was found.
    fn get(&self, key: &[u8], value: &mut Vec<u8>) -> Result<bool, StoreError> {
        value.clear();
        let_cxx_string!(native = "");
        let status = ffi::get(&self.dbm, key, native.as_mut());
        if check_end(&status)? {
            return Ok(false);
        }
        let bytes = native.as_bytes();
        value.reserve_exact(bytes.len());
        value.extend_from_slice(bytes);
        Ok(true)
    }

    /// `m_db->Get(key, nullptr)` (`phrase_large_table3_tkrzwdb.cpp:166`):
    /// whether `key` exists, an empty value included, copying nothing.
    fn check(&self, key: &[u8]) -> Result<bool, StoreError> {
        check_end(&ffi::check(&self.dbm, key)).map(|missing| !missing)
    }

    /// `m_db->Set(key, value)` (`ngram_tkrzwdb.cpp:132`): overwrite, as the
    /// pin's two-argument form does.
    fn set(&self, key: &[u8], value: &[u8]) -> Result<(), StoreError> {
        check(&ffi::set(&self.dbm, key, value))
    }

    /// `m_db->Remove(key)` (`ngram_tkrzwdb.cpp:140`): whether a record was
    /// removed. An absent key is `Ok(false)`, the library's
    /// `NOT_FOUND_ERROR` left for the caller's rule — the pin's `Bigram`
    /// answers false for it and its `PunctTable` true
    /// (`punct_table_tkrzwdb.cpp:157-159`).
    fn remove(&self, key: &[u8]) -> Result<bool, StoreError> {
        check_end(&ffi::remove(&self.dbm, key)).map(|missing| !missing)
    }

    /// The `TreeDBM` owners' `reset()` synchronization, `m_db->
    /// Synchronize(false)` before `Close` (`chewing_large_table2_tkrzwdb.cpp:
    /// 65-67`, `phrase_large_table3_tkrzwdb.cpp:52-54`, `punct_table_
    /// tkrzwdb.cpp:45-47`), its status ignored as the pin ignores it.
    fn reset_synchronize(&self) {
        #[cfg(test)]
        RESET_SYNCS.with(|count| count.set(count.get() + 1));
        let _ = ffi::synchronize(&self.dbm, false);
    }

    /// `m_db->Synchronize(hard)` with no file processor, the pin's
    /// one-argument form (`ngram_tkrzwdb.cpp:80`).
    fn synchronize(&self, hard: bool) -> Result<(), StoreError> {
        check(&ffi::synchronize(&self.dbm, hard))
    }

    /// `DBM::Count`, the library's record count.
    fn count(&self) -> Result<u64, StoreError> {
        let mut count = 0_i64;
        check(&ffi::count(&self.dbm, &mut count))?;
        Ok(u64::try_from(count).unwrap_or(0))
    }

    /// `DBM::IsHealthy`: whether the open file was closed cleanly and its
    /// size agrees with its metadata (`HashDBMImpl::OpenImpl`).
    fn is_healthy(&self) -> bool {
        ffi::is_healthy(&self.dbm)
    }

    /// `m_db->MakeIterator()` (`tkrzwdb_utils.h:52`). The cursor borrows
    /// this database (ruling point 3): the native iterator keeps a pointer
    /// back to it, which only the database's destruction clears
    /// (`tkrzw_dbm_hash.cc:2285-2296`), and `Close` invalidates its
    /// position (`tkrzw_dbm_tree.cc:516-518`), so the borrow outlasting the
    /// cursor is what makes every cursor call sound.
    fn cursor(&self) -> Result<Cursor<'_>, StoreError> {
        let iter = ffi::make_iterator(&self.dbm);
        if iter.is_null() {
            // `MakeIterator` allocates or throws; the pin still guards the
            // null (`tkrzwdb_utils.h:53`), so this backend does too.
            return Err(StoreError::Backend(crate::BackendError::from(
                "tkrzw returned no iterator",
            )));
        }
        Ok(Cursor {
            iter,
            _db: PhantomData,
        })
    }

    /// Every key in `DBM::ProcessEach` order — a hash container's bucket
    /// order, not the iterator's — the pin's `get_all_items` walk
    /// (`ngram_tkrzwdb.cpp:161-172`) with its key-length rule left to the
    /// caller.
    fn keys(&self) -> Result<Vec<Vec<u8>>, StoreError> {
        let mut keys = CxxVector::<CxxString>::new();
        check(&ffi::collect_keys(&self.dbm, keys.pin_mut()))?;
        Ok(keys.iter().map(|key| key.as_bytes().to_vec()).collect())
    }
}

