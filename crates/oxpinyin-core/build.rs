//! Generate PHF maps and relocation-free string tables from pinned literals.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[path = "src/table_data/full_pinyin_indexes.rs"]
mod full_indexes;
#[path = "src/table_data/full_pinyin_syllables.rs"]
mod full_syllables;
#[path = "../../tools/codegen/string_tables.rs"]
mod string_tables;

mod zhuyin_indexes {
    macro_rules! zhuyin_index {
        ($name:ident; $count:ident; [$(($input:literal, $canonical:literal, $pinyin:literal, $flags:expr)),* $(,)?]) => {
            pub const $name: &[(&str, &str, &str, &str)] = &[
                $(($input, $canonical, $pinyin, stringify!($flags))),*
            ];
        };
    }
    include!("src/table_data/zhuyin_indexes.rs");
}

/// `(source table, generated map)` pairs, in tier order: the order
/// `SyllableKey::from_text` / `from_canonical_text` consult them.
const TABLES: &[(&str, &str)] = &[
    ("INCOMPLETE_PINYIN_KEYS", "INCOMPLETE_PINYIN_KEY_MAP"),
    (
        "OPTION_ONLY_COMPLETE_SYLLABLES",
        "OPTION_ONLY_COMPLETE_SYLLABLE_MAP",
    ),
    (
        "ZHUYIN_ONLY_COMPLETE_SYLLABLES",
        "ZHUYIN_ONLY_COMPLETE_SYLLABLE_MAP",
    ),
];

fn main() {
    println!("cargo:rerun-if-changed=src/syllables.rs");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let source = fs::read_to_string("src/syllables.rs").expect("read src/syllables.rs");

    generate_string_tables(&out_dir);

    let mut generated =
        String::from("// Generated by build.rs from src/syllables.rs; do not edit.\n\n");
    write_phf(
        &mut generated,
        "FULL_PINYIN_SYLLABLE_MAP",
        full_syllables::FULL_PINYIN_SYLLABLES.iter().copied(),
    );
    for (table, map) in TABLES {
        let (declared, entries) = extract(&source, table)
            .unwrap_or_else(|| panic!("{table}: table not found in src/syllables.rs"));
        assert_eq!(
            entries.len(),
            declared,
            "{table}: declared [&str; {declared}] but found {} entries",
            entries.len()
        );
        write_phf(&mut generated, map, entries.iter().map(String::as_str));
    }

    fs::write(out_dir.join("syllable_maps.rs"), generated).expect("write syllable_maps.rs");
}

/// Extracts a frozen `pub static NAME: [&str; COUNT] = ["…", …];` table from
/// the syllable source, resolving `COUNT` through its
/// `pub const COUNT: usize = …;` definition: the declared length and the
/// string entries.
fn extract(source: &str, name: &str) -> Option<(usize, Vec<String>)> {
    let marker = format!("static {name}: [&str;");
    let table = source.find(&marker)?;
    let length_start = table + marker.len();
    let length_end = source[length_start..].find(']')? + length_start;
    let count_ident = source[length_start..length_end].trim();

    let count_marker = format!("const {count_ident}: usize = ");
    let count_start = source.find(&count_marker)? + count_marker.len();
    let count_end = source[count_start..].find(';')? + count_start;
    let declared = source[count_start..count_end].trim().parse().ok()?;

    // The assignment may wrap (`= \n    [`): find the `=` closing the
    // declaration, then the opening bracket after it.
    let eq = source[length_end..]
        .find('=')
        .unwrap_or_else(|| panic!("{name}: no array assignment found"))
        + length_end;
    let open = source[eq..]
        .find('[')
        .unwrap_or_else(|| panic!("{name}: no array body found"))
        + eq
        + 1;
    let close = source[open..]
        .find("];")
        .unwrap_or_else(|| panic!("{name}: unterminated array body"))
        + open;
    let body = &source[open..close];

    // The body holds only comma-separated string literals; the entries are
    // the quoted pieces.
    let mut pieces = body.split('"');
    pieces.next();
    let mut entries = Vec::new();
    while let Some(entry) = pieces.next() {
        entries.push(entry.to_owned());
        pieces.next();
    }
    Some((declared, entries))
}

fn write_phf<'a>(generated: &mut String, name: &str, entries: impl Iterator<Item = &'a str>) {
    let mut phf = phf_codegen::Map::new();
    for (index, entry) in entries.enumerate() {
        phf.entry(entry.to_owned(), index.to_string());
    }
    writeln!(
        generated,
        "pub(crate) static {name}: ::phf::Map<&'static str, u16> = {};\n",
        phf.build()
    )
    .expect("write generated map");
}

fn generate_string_tables(out_dir: &std::path::Path) {
    for path in [
        "src/table_data/full_pinyin_indexes.rs",
        "src/table_data/full_pinyin_syllables.rs",
        "src/table_data/zhuyin_indexes.rs",
        "../../tools/codegen/string_tables.rs",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
    assert_eq!(
        full_indexes::LUOMA_PINYIN_INDEX.len(),
        full_indexes::LUOMA_PINYIN_COUNT
    );
    assert_eq!(
        full_indexes::SECONDARY_ZHUYIN_INDEX.len(),
        full_indexes::SECONDARY_ZHUYIN_COUNT
    );
    assert_eq!(
        full_syllables::FULL_PINYIN_SYLLABLES.len(),
        full_syllables::FULL_PINYIN_SYLLABLE_COUNT
    );
    let mut pool = string_tables::StringPool::default();
    let mut output = String::from("// Generated from table_data; do not edit.\n");
    for (name, accessor, rows) in [
        (
            "LUOMA_PINYIN_INDEX",
            "luoma_pinyin_index",
            full_indexes::LUOMA_PINYIN_INDEX.as_slice(),
        ),
        (
            "SECONDARY_ZHUYIN_INDEX",
            "secondary_zhuyin_index",
            full_indexes::SECONDARY_ZHUYIN_INDEX.as_slice(),
        ),
    ] {
        pool.table(
            &mut output,
            name,
            accessor,
            rows.iter().map(|&(input, canonical)| [input, canonical]),
            "::oxpinyin_chewing",
        );
    }
    pool.table(
        &mut output,
        "FULL_PINYIN_SYLLABLES",
        "full_pinyin_syllables",
        full_syllables::FULL_PINYIN_SYLLABLES
            .iter()
            .map(|&text| [text]),
        "::oxpinyin_chewing",
    );
    for (name, accessor, rows) in [
        (
            "ZHUYIN_PINYIN_MAP",
            "zhuyin_pinyin_map",
            zhuyin_indexes::ZHUYIN_PINYIN_MAP,
        ),
        (
            "HSU_ZHUYIN_INDEX",
            "hsu_zhuyin_index",
            zhuyin_indexes::HSU_ZHUYIN_INDEX,
        ),
        (
            "ETEN26_ZHUYIN_INDEX",
            "eten26_zhuyin_index",
            zhuyin_indexes::ETEN26_ZHUYIN_INDEX,
        ),
    ] {
        pool.table(
            &mut output,
            name,
            accessor,
            rows.iter()
                .map(|&(input, canonical, pinyin, _)| [input, canonical, pinyin]),
            "::oxpinyin_chewing",
        );
        writeln!(
            output,
            "pub(crate) static {name}_FLAGS: [u32; {}] = [",
            rows.len()
        )
        .expect("write flags declaration");
        for (_, _, _, flags) in rows {
            writeln!(output, "{flags},").expect("write flags");
        }
        writeln!(output, "];\n").expect("write flags end");
    }
    pool.finish(&mut output);
    fs::write(out_dir.join("string_tables.rs"), output).expect("write string tables");
}
