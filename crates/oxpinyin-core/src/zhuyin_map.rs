/// A checked span in the immutable UTF-8 pool. Bounds are proved by build.rs.
#[derive(Clone, Copy)]
struct TextSpan {
    start: u16,
    len: u8,
}
impl TextSpan {
    fn text(self) -> &'static str {
        ZHUYIN_POOL
            .get(usize::from(self.start)..usize::from(self.start) + usize::from(self.len))
            .unwrap_or("")
    }
}
#[derive(Clone, Copy)]
struct CompactRow {
    input: TextSpan,
    canonical: TextSpan,
    pinyin: TextSpan,
    flags: u32,
}
impl CompactRow {
    fn decoded(&self) -> (&'static str, &'static str, &'static str, u32) {
        (
            self.input.text(),
            self.canonical.text(),
            self.pinyin.text(),
            self.flags,
        )
    }
}
pub(crate) struct CompactIndex;
/// `(input spelling, canonical spelling, canonical pinyin, row flags)`
/// quadruples, sorted by input spelling bytes — the binary-search
/// invariant of the pinned table.
///
/// The canonical spelling is `content_table[idx].m_chewing` — what
/// upstream's `ChewingKey::get_zhuyin_string` renders, so a shuffled
/// input (ㄅㄝㄧ) displays as its canonical spelling (ㄅㄧㄝ) exactly like
/// the oracle's auxiliary text. Plain and incomplete rows carry the input
/// spelling back; only shuffle rows differ.
///
/// Row flags are the upstream option bits consulted by
/// `check_chewing_options` (`src/storage/zhuyin_parser2.cpp:43-63`):
/// [`ZHUYIN_INCOMPLETE`] rows parse only under that option,
/// [`ZHUYIN_CORRECT_SHUFFLE`] rows only under theirs. The `IS_ZHUYIN`
/// (always present) and `PINYIN_INCOMPLETE` (pinyin-surface bookkeeping)
/// bits are structural upstream and gate nothing here, so they are not
/// carried.
pub(crate) static ZHUYIN_PINYIN_MAP: CompactIndex = CompactIndex;
impl CompactIndex {
    #[cfg(test)]
    pub(crate) fn iter(
        &self,
    ) -> impl Iterator<Item = (&'static str, &'static str, &'static str, u32)> {
        ZHUYIN_ROWS.iter().map(CompactRow::decoded)
    }
}

pub(crate) trait ZhuyinIndex {
    fn find_row(&self, input: &str) -> Option<(&'static str, &'static str, &'static str, u32)>;
}
impl ZhuyinIndex for CompactIndex {
    fn find_row(&self, input: &str) -> Option<(&'static str, &'static str, &'static str, u32)> {
        let position = ZHUYIN_ROWS.partition_point(|row| row.input.text() < input);
        ZHUYIN_ROWS.get(position).map(CompactRow::decoded)
    }
}
impl<const N: usize> ZhuyinIndex for [(&'static str, &'static str, &'static str, u32); N] {
    fn find_row(&self, input: &str) -> Option<(&'static str, &'static str, &'static str, u32)> {
        let position = self.partition_point(|row| row.0 < input);
        self.get(position).copied()
    }
}
impl ZhuyinIndex for [(&'static str, &'static str, &'static str, u32)] {
    fn find_row(&self, input: &str) -> Option<(&'static str, &'static str, &'static str, u32)> {
        let position = self.partition_point(|row| row.0 < input);
        self.get(position).copied()
    }
}

