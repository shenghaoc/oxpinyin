"""Offline Rust formatting of the pin's unmodified scripts2 table generators.

The committed C headers are the acceptance oracle, not a replacement algorithm.
Only explicitly recorded fallback markers are read from their checked blobs.
The pinyins.txt input is derived with the pin's scripts2 distiller and is
GPL-3.0-or-later, as the pin; its model20 source is documented in README.md.
"""

