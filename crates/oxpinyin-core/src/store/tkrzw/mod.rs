// ── store ─────────────────────────────────────────────────────────

/// A tkrzw-backed store implementing both capability tiers.
///
/// Feature-gated behind `tkrzw`. See the module documentation for the
/// one raw keyspace and for how `write`'s atomicity is weaker than a
/// write-ahead-log backend's.
pub struct TkrzwStore {
    db: Db,
    read_only: bool,
}

/// Allocates `class` and opens `path` with the pin's `attach_options`
/// (`tkrzwdb_utils.h:32-46`): `writable` for `ATTACH_READWRITE`, and
/// `OPEN_NO_CREATE` unless `create` (`ATTACH_CREATE`). A failed open is
/// the error the status names; the object is dropped with it, closed and
/// deleted as the module docs describe.
fn open_store(
    class: Class,
    path: &Path,
    writable: bool,
    create: bool,
) -> Result<TkrzwStore, StoreError> {
    let mut db = Db::new(class);
    let options = if create { OPEN_DEFAULT } else { OPEN_NO_CREATE };
    check(&db.open(path, writable, options)?)?;
    Ok(TkrzwStore {
        db,
        read_only: !writable,
    })
}

/// `Bigram::attach(dbfile, ATTACH_READONLY)` (`ngram_tkrzwdb.cpp:86-99`): a
/// `HashDBM` opened read-only with `OPEN_NO_CREATE`.
fn open_hash(path: &Path) -> Result<TkrzwStore, StoreError> {
    open_store(Class::Hash, path, false, false)
}

/// `Bigram::attach(dbfile, ATTACH_READWRITE | ATTACH_CREATE)`: a `HashDBM`
/// opened writable with `OPEN_DEFAULT`.
fn open_hash_create(path: &Path) -> Result<TkrzwStore, StoreError> {
    open_store(Class::Hash, path, true, true)
}

/// `m_db = new BabyDBM` (`chewing_large_table2_tkrzwdb.cpp:57`): tkrzw's
/// on-memory ordered container, never opened, bound to no file — ordered
/// like `TreeDBM`, so the ordered raw walks and `Jump`s hold.
fn open_in_memory() -> TkrzwStore {
    TkrzwStore {
        db: Db::new(Class::Baby),
        read_only: false,
    }
}

/// `ChewingLargeTable2::attach` (`chewing_large_table2_tkrzwdb.cpp:75-89`):
/// a `TreeDBM`, read-only with `OPEN_NO_CREATE`, or writable with
/// `OPEN_DEFAULT` as the pin's `save_db` temporaries and its
/// `ATTACH_READWRITE | ATTACH_CREATE` generators open it.
fn open(path: &Path, writable: bool) -> Result<TkrzwStore, StoreError> {
    open_store(Class::Tree, path, writable, writable)
}

// ── failed system attachments ─────────────────────────────────────

/// The pin's system attach for one tkrzw table: the concrete object
/// allocated and `Open`ed read-only without `ATTACH_CREATE`, or with
/// `read_only` false the utilities' writable `OPEN_DEFAULT`
/// (`attach_options`, `tkrzwdb_utils.h:32-46`; `ChewingLargeTable2::
/// attach`, `chewing_large_table2_tkrzwdb.cpp:75-89`; `PhraseLargeTable3::
/// attach`, `phrase_large_table3_tkrzwdb.cpp:65-80`; `PunctTable::attach`,
/// `punct_table_tkrzwdb.cpp:58-73`; `Bigram::attach`, `ngram_tkrzwdb.cpp:
/// 86-99`). On success the store; on failure the object the pin keeps,
/// which answers the facade's later calls.
///
/// # Errors
///
/// Returns the failures before the native open: a path containing NUL.
pub(crate) fn open_system(
    path: &Path,
    hash: bool,
    read_only: bool,
) -> Result<Result<TkrzwStore, TkrzwUnopenedHandle>, StoreError> {
    let class = if hash { Class::Hash } else { Class::Tree };
    let mut db = Db::new(class);
    let options = if read_only {
        OPEN_NO_CREATE
    } else {
        OPEN_DEFAULT
    };
    let status = db.open(path, !read_only, options)?;
    Ok(if status.code == STATUS_SUCCESS {
        // The Tree owners' reset synchronizes before it closes; the
        // bigram's `HashDBM` is closed with no explicit sync
        // (`ngram_tkrzwdb.cpp:36-45`).
        db.sync_before_close = class == Class::Tree;
        Ok(TkrzwStore { db, read_only })
    } else {
        Err(TkrzwUnopenedHandle { db, class })
    })
}

/// A system table's `TreeDBM` or `HashDBM` whose `Open` failed, kept as
/// the pin keeps it: every later call reaches the real object, which
/// answers `PRECONDITION_ERROR` (`tkrzw_dbm_hash.cc:400-401`,
/// `tkrzw_dbm_tree.cc:563-564`), and reset makes the owner's calls on it.
pub(crate) struct TkrzwUnopenedHandle {
    db: Db,
    class: Class,
}

impl TkrzwUnopenedHandle {
    /// The pin's failed point read, `m_db->Get(key, &value)`, whose status
    /// each owner then reads as a miss: `ChewingLargeTable2::search_internal`
    /// (`chewing_large_table2_tkrzwdb.cpp:146-149`), `PhraseLargeTable3::
    /// search` (`phrase_large_table3_tkrzwdb.cpp:136-139`), `Bigram::load`
    /// (`ngram_tkrzwdb.cpp:111-114`) and `PunctTable::load_entry`
    /// (`punct_table_tkrzwdb.cpp:124-130`). tkrzw writes nothing to stderr.
    pub(crate) fn read(&self, key: &[u8]) {
        let mut value = Vec::new();
        let _ = self.db.get(key, &mut value);
    }

    /// The failed suggestion's first call, `m_db->Get(query_key, nullptr)`,
    /// after which the pin returns without an iterator
    /// (`chewing_large_table2_tkrzwdb.cpp:511-512`,
    /// `phrase_large_table3_tkrzwdb.cpp:166-167`).
    pub(crate) fn suggest(&self, key: &[u8]) {
        let _ = self.db.check(key);
    }

    /// `Bigram::store`'s `m_db->Set(key, value)` (`ngram_tkrzwdb.cpp:
    /// 124-133`), which the unopened object refuses; that status is the
    /// answer.
    pub(crate) fn write(&self, key: &[u8], value: &[u8]) -> Result<(), StoreError> {
        self.db.set(key, value)
    }

    /// `Bigram::get_all_items`' `m_db->ProcessEach(&processor, false)`
    /// (`ngram_tkrzwdb.cpp:160-172`), which the unopened object refuses
    /// with no key collected; the pin returns that status.
    pub(crate) fn walk(&self) -> Result<(), StoreError> {
        self.db.keys().map(drop)
    }
}

impl Drop for TkrzwUnopenedHandle {
    fn drop(&mut self) {
        // The owner's `reset()`: the three `TreeDBM` owners synchronize
        // before closing (`chewing_large_table2_tkrzwdb.cpp:65-67`,
        // `phrase_large_table3_tkrzwdb.cpp:52-54`, `punct_table_tkrzwdb.cpp:
        // 45-47`); `Bigram` closes and deletes (`ngram_tkrzwdb.cpp:42-43`).
        // Every status is ignored, as the pin ignores it; `Db::drop` then
        // makes the `Close` and the delete.
        if self.class == Class::Tree {
            self.db.reset_synchronize();
        }
    }
}

// ── engine-level operations ───────────────────────────────────────

/// Whether the opened hash file `db` holds no record by tkrzw's own
/// account: it opened healthy (`DBM::IsHealthy`) and counts no record
/// (`DBM::Count`). A failed count or an unhealthy file answers no, so the
/// copy walks it.
fn holds_no_record(db: &Db) -> bool {
    db.is_healthy() && matches!(db.count(), Ok(0))
}

/// A row visitor as [`drive_scan`] drives it: one borrowed key and value
/// per record, [`Flow::Break`] to stop early.
type RowVisitor<'a> = dyn FnMut(&[u8], &[u8]) -> Result<Flow, StoreError> + 'a;

/// Walks the file's records whose key lies in `(lo, hi)`, ascending,
/// handing each to `row` borrowed from the walk's record strings. `row`
/// returns [`Flow::Break`] to stop early.
///
/// Every row the walk yields is already inside the bounds, so callers
/// do not re-check them.
///
/// Only this wrapper is instantiated per visitor; the iterator, the
/// positioning and the record loop are [`drive_scan`], one copy for every
/// call site.
fn scan_rows<F>(db: &Db, lo: Bound<&[u8]>, hi: Bound<&[u8]>, mut row: F) -> Result<(), StoreError>
where
    F: FnMut(&[u8], &[u8]) -> Result<Flow, StoreError>,
{
    drive_scan(db, lo, hi, &mut row)
}

/// The iterator and record loop of [`scan_rows`]: the pin's `copy_tkrzwdb`
/// shape (`tkrzwdb_utils.h:52-70`) — `MakeIterator`, `First` or the
/// lower-bound `Jump`, then `Get(&key, &value)` and `Next` per record —
/// with the bounds applied to each record's key.
#[inline(never)]
fn drive_scan(
    db: &Db,
    lo: Bound<&[u8]>,
    hi: Bound<&[u8]>,
    row: &mut RowVisitor<'_>,
) -> Result<(), StoreError> {
    drive_cursor(db.cursor()?, lo, hi, row)
}

/// [`drive_scan`] past `MakeIterator`: the positioning and the record loop
/// over an iterator the caller made.
fn drive_cursor(
    mut cursor: Cursor<'_>,
    lo: Bound<&[u8]>,
    hi: Bound<&[u8]>,
    row: &mut RowVisitor<'_>,
) -> Result<(), StoreError> {
    // `Jump` is a lower-bound seek, so an Excluded lower bound lands on the
    // excluded key itself and is skipped by the bounds check below.
    let start: &[u8] = match lo {
        Bound::Unbounded => &[],
        Bound::Included(key) | Bound::Excluded(key) => key,
    };
    // An empty start is the unbounded walk's first record: `First`. A
    // `Jump` with the empty string is not equivalent on the hash
    // containers — `HashDBM` answers `NOT_FOUND_ERROR` for `Jump("")` on a
    // file that has records — and a *bounded* jump answers
    // `NOT_FOUND_ERROR` for a non-empty start when no record meets the
    // lower bound (an empty database, or one whose keys all fall before
    // it), which is an empty scan, not an error. `TreeDBM`'s `First` and
    // `Jump` answer `SUCCESS` with the position cleared instead
    // (`tkrzw_dbm_tree.cc:2142-2176`), and the first `Get` then ends the
    // walk.
    let positioned = if start.is_empty() {
        cursor.first()
    } else {
        cursor.jump(start)
    };
    if check_end(&positioned)? {
        return Ok(());
    }
    let_cxx_string!(key = "");
    let_cxx_string!(value = "");
    loop {
        // Past the last record `Get` reports `NOT_FOUND_ERROR`
        // (`tkrzw_dbm_tree.cc:2273-2276`), the walk's successful end.
        if check_end(&cursor.get(key.as_mut(), value.as_mut()))? {
            break;
        }
        let user_key = key.as_bytes();
        if past_upper(user_key, hi) {
            break;
        }
        if in_bounds(user_key, lo, hi) && row(user_key, value.as_bytes())?.is_break() {
            break;
        }
        if check_end(&cursor.next())? {
            break;
        }
    }
    Ok(())
}

