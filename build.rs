//! Generate PHF maps and relocation-free string tables from pinned literals.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

#[path = "src/content_table_source.rs"]
mod content_source;
#[path = "src/table_data/full_pinyin_indexes.rs"]
mod full_indexes;
#[path = "src/table_data/full_pinyin_syllables.rs"]
mod full_syllables;
#[expect(
    dead_code,
    reason = "The shared inventory also declares library-only constants."
)]
#[path = "src/table_data/syllable_inventory.rs"]
mod inventory;
#[path = "codegen/string_tables.rs"]
mod string_tables;

mod zhuyin_indexes {
    macro_rules! zhuyin_index {
        ($name:ident; $count:ident; [$(($input:literal, $canonical:literal, $pinyin:literal, $flags:expr)),* $(,)?]) => {
            pub const $name: &[(&str, &str, &str, &str)] = &[
                $(($input, $canonical, $pinyin, stringify!($flags))),*
            ];
        };
    }
    include!("src/table_data/zhuyin_indexes.rs");
}

/// `(inventory, generated map)` pairs, in tier order: the order
/// `SyllableKey::from_text` / `from_canonical_text` consult them.
const TABLES: &[(&[&str], &str)] = &[
    (
        &inventory::INCOMPLETE_PINYIN_KEYS,
        "INCOMPLETE_PINYIN_KEY_MAP",
    ),
    (
        &inventory::OPTION_ONLY_COMPLETE_SYLLABLES,
        "OPTION_ONLY_COMPLETE_SYLLABLE_MAP",
    ),
    (
        &inventory::ZHUYIN_ONLY_COMPLETE_SYLLABLES,
        "ZHUYIN_ONLY_COMPLETE_SYLLABLE_MAP",
    ),
];

#[path = "codegen/store.rs"]
mod store;

fn main() {
    store::build();
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/table_data/syllable_inventory.rs");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));

    generate_content_table(&out_dir);
    let spellings = syllable_spellings();
    generate_string_tables(&out_dir, &spellings);

    let mut generated = String::from(
        "// Generated by build.rs from src/table_data/syllable_inventory.rs; do not edit.\n\n",
    );
    write_phf(
        &mut generated,
        "FULL_PINYIN_SYLLABLE_MAP",
        full_syllables::FULL_PINYIN_SYLLABLES.iter().copied(),
    );
    for (entries, map) in TABLES {
        write_phf(&mut generated, map, entries.iter().copied());
    }

    fs::write(out_dir.join("syllable_maps.rs"), generated).expect("write syllable_maps.rs");

    generate_chewing_keys(&out_dir, &spellings);
}

fn generate_content_table(out_dir: &std::path::Path) {
    println!("cargo:rerun-if-changed=src/content_table_source.rs");
    let mut pool = string_tables::StringPool::default();
    let mut output = String::from("// Generated from content_table_source.rs; do not edit.\n");
    pool.table(
        &mut output,
        "CONTENT_STRINGS",
        "content_strings",
        content_source::CONTENT_TABLE.iter().map(|row| {
            [
                row.pinyin,
                row.shengmu,
                row.yunmu,
                row.zhuyin,
                row.luoma,
                row.secondary,
            ]
        }),
        "crate::static_strings",
    );
    // The spelling column is also stored inline as an integer key: the
    // spelling's bytes, zero-padded to eight, read big-endian. No spelling
    // holds a NUL byte, so the integer order is the byte order of the
    // spellings and integer equality is spelling equality.
    writeln!(
        output,
        "pub(crate) static CONTENT_KEYS: [ContentKey; {}] = [",
        content_source::CONTENT_TABLE.len()
    )
    .expect("write key declaration");
    let mut previous = None;
    for row in content_source::CONTENT_TABLE {
        let bytes = row.pinyin.as_bytes();
        assert!(
            bytes.len() <= 8 && !bytes.contains(&0),
            "content spelling {:?} does not fit an 8-byte key",
            row.pinyin
        );
        let mut padded = [0_u8; 8];
        padded[..bytes.len()].copy_from_slice(bytes);
        let spelling = u64::from_be_bytes(padded);
        assert!(
            previous.is_none_or(|previous| previous < spelling),
            "content spellings must be strictly increasing"
        );
        previous = Some(spelling);
        writeln!(
            output,
            "ContentKey {{ spelling: {spelling:#018x}, initial: {}, middle: {}, final_: {} }},",
            row.initial, row.middle, row.final_
        )
        .expect("write key");
    }
    writeln!(output, "];").expect("write key end");
    pool.finish(&mut output);
    fs::write(out_dir.join("content_table.rs"), output).expect("write content table");
}

/// The `SyllableKey` spellings in id order: the full syllables, then each
/// of `TABLES` in order.
fn syllable_spellings() -> Vec<String> {
    let mut spellings: Vec<String> = full_syllables::FULL_PINYIN_SYLLABLES
        .iter()
        .map(|&text| text.to_owned())
        .collect();
    for (entries, _) in TABLES {
        spellings.extend(entries.iter().map(|&text| text.to_owned()));
    }
    spellings
}

/// One tone-zero `ChewingKey` per `SyllableKey` id, in id order, taken from
/// the spelling's `content_table` row. A spelling without a content row is
/// a build error.
fn generate_chewing_keys(out_dir: &std::path::Path, spellings: &[String]) {
    let mut generated =
        String::from("// Generated by build.rs from content_table_source.rs; do not edit.\n");
    writeln!(
        generated,
        "pub(crate) static CHEWING_KEYS: [crate::parser::ChewingKey; {}] = [",
        spellings.len()
    )
    .expect("write key table declaration");
    for spelling in spellings {
        let row = content_source::CONTENT_TABLE
            .iter()
            .skip(1)
            .find(|row| row.pinyin == spelling)
            .unwrap_or_else(|| panic!("{spelling:?}: no content_table row"));
        writeln!(
            generated,
            "crate::parser::ChewingKey {{ initial: {}, middle: {}, final_: {}, tone: crate::chewing_key::CHEWING_ZERO_TONE }},",
            row.initial, row.middle, row.final_
        )
        .expect("write key");
    }
    writeln!(generated, "];").expect("write key table end");
    fs::write(out_dir.join("chewing_keys.rs"), generated).expect("write chewing_keys.rs");
}

fn write_phf<'a>(generated: &mut String, name: &str, entries: impl Iterator<Item = &'a str>) {
    let mut phf = phf_codegen::Map::new();
    for (index, entry) in entries.enumerate() {
        phf.entry(entry.to_owned(), index.to_string());
    }
    writeln!(
        generated,
        "pub(crate) static {name}: ::phf::Map<&'static str, u16> = {};\n",
        phf.build()
    )
    .expect("write generated map");
}

fn generate_string_tables(out_dir: &std::path::Path, spellings: &[String]) {
    for path in [
        "src/table_data/full_pinyin_indexes.rs",
        "src/table_data/full_pinyin_syllables.rs",
        "src/table_data/zhuyin_indexes.rs",
        "codegen/string_tables.rs",
    ] {
        println!("cargo:rerun-if-changed={path}");
    }
    assert_eq!(
        full_indexes::LUOMA_PINYIN_INDEX.len(),
        full_indexes::LUOMA_PINYIN_COUNT
    );
    assert_eq!(
        full_indexes::SECONDARY_ZHUYIN_INDEX.len(),
        full_indexes::SECONDARY_ZHUYIN_COUNT
    );
    assert_eq!(
        full_syllables::FULL_PINYIN_SYLLABLES.len(),
        full_syllables::FULL_PINYIN_SYLLABLE_COUNT
    );
    let mut pool = string_tables::StringPool::default();
    let mut output = String::from("// Generated from table_data; do not edit.\n");
    for (name, accessor, rows) in [
        (
            "LUOMA_PINYIN_INDEX",
            "luoma_pinyin_index",
            full_indexes::LUOMA_PINYIN_INDEX.as_slice(),
        ),
        (
            "SECONDARY_ZHUYIN_INDEX",
            "secondary_zhuyin_index",
            full_indexes::SECONDARY_ZHUYIN_INDEX.as_slice(),
        ),
    ] {
        pool.table(
            &mut output,
            name,
            accessor,
            rows.iter().map(|&(input, canonical)| [input, canonical]),
            "crate::static_strings",
        );
    }
    pool.table(
        &mut output,
        "FULL_PINYIN_SYLLABLES",
        "full_pinyin_syllables",
        full_syllables::FULL_PINYIN_SYLLABLES
            .iter()
            .map(|&text| [text]),
        "crate::static_strings",
    );
    for (name, accessor, rows) in [
        (
            "ZHUYIN_PINYIN_MAP",
            "zhuyin_pinyin_map",
            zhuyin_indexes::ZHUYIN_PINYIN_MAP,
        ),
        (
            "HSU_ZHUYIN_INDEX",
            "hsu_zhuyin_index",
            zhuyin_indexes::HSU_ZHUYIN_INDEX,
        ),
        (
            "ETEN26_ZHUYIN_INDEX",
            "eten26_zhuyin_index",
            zhuyin_indexes::ETEN26_ZHUYIN_INDEX,
        ),
    ] {
        // Only the input spelling is searched; each row stores its key's
        // `SyllableKey` id in place of the canonical zhuyin and pinyin
        // texts. The pin reads the key from the row's `content_table` entry
        // (`zhuyin_parser2.cpp:95` at 074a2219), and renders the zhuyin from
        // that entry (`chewing_key.cpp:74-89`), so the canonical column must
        // be the content row's zhuyin.
        pool.table(
            &mut output,
            name,
            accessor,
            rows.iter().map(|&(input, _, _, _)| [input]),
            "crate::static_strings",
        );
        writeln!(
            output,
            "pub(crate) static {name}_KEYS: [u16; {}] = [",
            rows.len()
        )
        .expect("write keys declaration");
        for &(input, canonical, pinyin, _) in rows {
            let content = content_source::CONTENT_TABLE
                .iter()
                .skip(1)
                .find(|row| row.pinyin == pinyin)
                .unwrap_or_else(|| panic!("{name} {input:?}: no content_table row for {pinyin:?}"));
            assert_eq!(
                content.zhuyin, canonical,
                "{name} {input:?}: the canonical spelling is not the content row's zhuyin"
            );
            let id = spellings
                .iter()
                .position(|spelling| spelling == pinyin)
                .unwrap_or_else(|| panic!("{name} {input:?}: {pinyin:?} has no syllable key"));
            writeln!(output, "{id},").expect("write key");
        }
        writeln!(output, "];\n").expect("write keys end");
        writeln!(
            output,
            "pub(crate) static {name}_FLAGS: [u32; {}] = [",
            rows.len()
        )
        .expect("write flags declaration");
        for (_, _, _, flags) in rows {
            writeln!(output, "{flags},").expect("write flags");
        }
        writeln!(output, "];\n").expect("write flags end");
    }
    pool.finish(&mut output);
    fs::write(out_dir.join("string_tables.rs"), output).expect("write string tables");
}
